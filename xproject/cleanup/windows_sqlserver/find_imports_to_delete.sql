SELECT fi.REFERENCE AS FILENAME
FROM WLM_EXECUTION_WKF_FILE_INFO ewfi
JOIN WLM_FILE_INFO fi ON fi.ID = ewfi.FILE_INFO_ID
WHERE ewfi.EXECUTION_WORKFLOW_ID IN (
    SELECT ID
    FROM WLM_EXECUTION_WORKFLOW e1
    WHERE e1.CREATED_DATE NOT IN (
        SELECT MAX(e2.CREATED_DATE)
        FROM WLM_EXECUTION_WORKFLOW e2
        WHERE STATUS='VALIDATED'
        GROUP BY e2.IMPORT_CONTAINER_ID
    )
);