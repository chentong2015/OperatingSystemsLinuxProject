SELECT fi.REFERENCE AS FILENAME
FROM WLM_EXPORT AS expo
INNER JOIN WLM_FILE_INFO AS fi ON fi.ID = expo.EXPORTED_FILE_ID
WHERE expo.ID IN (
    SELECT e.ID
    FROM WLM_EXPORT AS e
    WHERE e.CREATED_DATE >= DATEADD(DAY, -7, CAST(GETDATE() AS DATE))
    AND e.CREATED_DATE < DATEADD(DAY, 0, CAST(GETDATE() AS DATE))
) AND fi.ORIGINAL_NAME NOT LIKE 'fkof_V%';